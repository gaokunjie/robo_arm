def require_scene(what="这条路径"):
    ok, missing = scene_ready()
    if not ok:
        raise SystemExit(
            "✗ 拒绝运行：场景常数未实测齐（%s）。\n"
            "  缺：%s\n"
            "  这些是 C1 批次 C 的产出（量盒顶高度 + 杯轴水平位置），不是能猜的数。\n"
            "  台架上的旧值（442 / 245）与视觉解已互相矛盾，必须用量尺的值覆盖。"
            % (what, "、".join(missing)))
    return True


